#!/usr/bin/env python3
"""Generate immutable NumPy 2.5 loop declarations (not runtime kernels)."""
import json
import math
import pathlib
import numpy as np

assert np.__version__ == "2.5.0"
entries={}
aliases={}
for name in sorted(np.__all__):
    obj=getattr(np,name,None)
    if isinstance(obj,np.ufunc):
        entries[obj.__name__]=obj
        if name!=obj.__name__:aliases[name]=obj.__name__

def literal(x):
    if x is None:return "nil"
    if isinstance(x,bool):return str(x).lower()
    if isinstance(x,int):return f"int64({x})"
    if isinstance(x,float):
        if math.isinf(x):return f"math.Inf({1 if x>0 else -1})"
        return f"float64({x!r})"
    raise ValueError(x)

lines=["// Code generated by tools/generate_ufunc_metadata.py from NumPy 2.5.0; DO NOT EDIT.",
       "package np","","import \"math\"","",
       "var ufuncAliases = map[string]string{"]
for name,target in sorted(aliases.items()):
    lines.append(f"\t{json.dumps(name)}: {json.dumps(target)},")
lines+=["}","","var ufuncReference = map[string]ufuncReferenceMeta{"]
for name,u in sorted(entries.items()):
    types=", ".join(json.dumps(x) for x in u.types)
    lines.append(f"\t{json.dumps(name)}: {{nin:{u.nin}, nout:{u.nout}, signature:{json.dumps(u.signature or '')}, identity:{literal(u.identity)}, types:[]string{{{types}}}}},")
lines+=["}",""]
pathlib.Path(__file__).resolve().parents[1].joinpath("ufunc_reference_types.go").write_text("\n".join(lines))
print(f"generated {len(entries)} canonical ufuncs and {len(aliases)} aliases")
