#!/usr/bin/env python3
"""Generate Unicode scalar mappings used by NumPy's Python string kernels."""
import json
import pathlib
import unicodedata

assert unicodedata.unidata_version == "15.0.0", "use the reference environment's Unicode data"

root = pathlib.Path(__file__).resolve().parents[1]
target = root / "strings" / "unicode_tables.go"
chars = [chr(i) for i in range(0x110000) if not 0xD800 <= i <= 0xDFFF]


def cased(c):
    return c.islower() or c.isupper() or c.istitle()


def ignorable(c):
    # Python lower implements Unicode Final_Sigma using Case_Ignorable.
    if cased(c):
        return ("AΣ" + c + " ").lower()[1] == "ς"
    return ("AΣ" + c + "A").lower()[1] == "σ"


with target.open("w", encoding="utf-8") as f:
    f.write("// Code generated by tools/generate_unicode_tables.py. DO NOT EDIT.\n")
    f.write(f"// Python Unicode data version: {unicodedata.unidata_version}.\n")
    f.write("package npstrings\n\n")
    for name, predicate in [
        ("alpha", str.isalpha), ("digit", str.isdigit), ("decimal", str.isdecimal),
        ("numeric", str.isnumeric), ("space", str.isspace), ("lower", str.islower),
        ("upper", str.isupper), ("title", str.istitle), ("ignorable", ignorable),
    ]:
        ranges = []
        for c in chars:
            if predicate(c):
                i = ord(c)
                if ranges and ranges[-1][1] == i - 1:
                    ranges[-1][1] = i
                else:
                    ranges.append([i, i])
        f.write(f"var {name}Ranges = [...]runeRange{{\n")
        for lo, hi in ranges:
            f.write(f"\t{{0x{lo:X}, 0x{hi:X}}},\n")
        f.write("}\n")
    for name, transform in [("upper", str.upper), ("lower", str.lower), ("title", str.title), ("swap", str.swapcase)]:
        f.write(f"var {name}Mappings = map[rune]string{{\n")
        for c in chars:
            r = transform(c)
            if r != c:
                f.write(f"\t0x{ord(c):X}: {json.dumps(r, ensure_ascii=False)},\n")
        f.write("}\n")
