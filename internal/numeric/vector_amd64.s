// All vector prefixes are whole 16-byte blocks. Load both operands
// unaligned, since sliced ndarray views need not be aligned.
#define BINARY_STEP(OP) \
	MOVUPS (SI), X0; \
	MOVUPS (DX), X1; \
	OP X1, X0; \
	MOVUPS X0, (DI); \
	ADDQ $16, SI; \
	ADDQ $16, DX; \
	ADDQ $16, DI; \
	DECQ CX

