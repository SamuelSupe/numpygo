TEXT ·partial64AVX(SB),NOSPLIT,$0-32
	MOVQ dst+0(FP),DI
	MOVQ src_base+8(FP),SI
	MOVQ src_len+16(FP),CX
	SHRQ $3,CX
	VMOVUPD (SI),Y0
	VMOVUPD 32(SI),Y1
	ADDQ $64,SI
	DECQ CX
	JZ sum64Done
