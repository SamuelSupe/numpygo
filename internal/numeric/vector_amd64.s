#define RADIX_MUL(PTR,ROOT,DST) \
	VMOVUPD (PTR), DST; \
	VMOVUPD (ROOT), Y4; \
	VMOVDDUP Y4, Y5; \
	VPERMILPD $15, Y4, Y6; \
	VPERMILPD $5, DST, Y7; \
	VMULPD Y5, DST, DST; \
	VMULPD Y6, Y7, Y7; \
