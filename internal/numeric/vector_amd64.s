// CPUID: AVX + OSXSAVE, then check that OS enabled XMM and YMM state.
TEXT ·hasAVX(SB), NOSPLIT, $0-1
	MOVL $1, AX
	CPUID
	ANDL $0x18000000, CX
	CMPL CX, $0x18000000
	JNE noavx
	XORL CX, CX
	XGETBV
	ANDL $6, AX
	CMPL AX, $6
	JNE noavx
	MOVB $1, ret+0(FP)
	RET
noavx:
	MOVB $0, ret+0(FP)
	RET

// Two adjacent complex values occupy one YMM register. Use the same
// multiply/add rounding as the scalar butterfly, without FMA.
#define BUTTERFLY_STEP(OFF) \
	VMOVUPD OFF(SI), Y0; \
	VMOVUPD OFF(DX), Y1; \
	VMOVDDUP Y1, Y2; \
	VPERMILPD $15, Y1, Y3; \
	VPERMILPD $5, Y0, Y4; \
	VMULPD Y2, Y0, Y0; \
	VMULPD Y3, Y4, Y4; \
	VADDSUBPD Y4, Y0, Y0; \
	VMOVUPD OFF(DI), Y5; \
	VADDPD Y0, Y5, Y6; \
	VSUBPD Y0, Y5, Y5; \
	VMOVUPD Y6, OFF(DI); \
	VMOVUPD Y5, OFF(SI)

TEXT ·butterflyAVX(SB), NOSPLIT, $0-72
	MOVQ left_base+0(FP), DI
	MOVQ right_base+24(FP), SI
