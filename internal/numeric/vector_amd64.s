// Broadcast a scalar once and keep it in Y1 throughout the lane.
#define BROADCAST_STEP(OP,A,B) \
	VMOVUPD (SI), Y0; \
	OP A, B, Y0; \
	VMOVUPD Y0, (DI); \
	ADDQ $32, SI; \
	ADDQ $32, DI; \
	DECQ CX

