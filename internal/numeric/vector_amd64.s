// Fused radix-4: three complex multiplications and four output
// butterflies, with two independent transforms in each YMM register.
TEXT ·radix4AVX(SB), NOSPLIT, $0-104
	MOVQ x_base+0(FP), DI
	MOVQ w1_base+24(FP), R10
	MOVQ w2_base+48(FP), R11
	MOVQ w3_base+72(FP), R12
	MOVQ w1_len+32(FP), CX
	MOVQ CX, AX
	SHLQ $4, AX
	LEAQ (DI)(AX*1), SI
	LEAQ (SI)(AX*1), R8
	LEAQ (R8)(AX*1), R9
	MOVQ sign+96(FP), AX
	TESTQ AX, AX
	JS radixneg
	VMOVUPD ·rotPos(SB), Y15
	JMP radixstart
radixneg:
	VMOVUPD ·rotNeg(SB), Y15
radixstart:
	SHRQ $1, CX
	JZ radixdone
radixloop:
	VMOVUPD (DI), Y0
	RADIX_MUL(SI,R10,Y1)
	RADIX_MUL(R8,R11,Y2)
	RADIX_MUL(R9,R12,Y3)
	VADDPD Y1, Y0, Y8
	VSUBPD Y1, Y0, Y0
	VADDPD Y3, Y2, Y9
	VSUBPD Y3, Y2, Y2
	VPERMILPD $5, Y2, Y2
	VXORPD Y15, Y2, Y2
	VADDPD Y9, Y8, Y1
	VSUBPD Y9, Y8, Y8
	VADDPD Y2, Y0, Y3
	VSUBPD Y2, Y0, Y0
	VMOVUPD Y1, (DI)
	VMOVUPD Y3, (SI)
	VMOVUPD Y8, (R8)
	VMOVUPD Y0, (R9)
	ADDQ $32, DI
	ADDQ $32, SI
	ADDQ $32, R8
	ADDQ $32, R9
	ADDQ $32, R10
	ADDQ $32, R11
	ADDQ $32, R12
	DECQ CX
	JNZ radixloop
radixdone:
	VZEROUPPER
	RET

