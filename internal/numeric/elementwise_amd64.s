// Inputs are two interleaved complex numbers per vector. Multiply
// uses the existing FFT arithmetic order. Divide selects the Smith
// ratio lane-wise, including the sign-sensitive subtraction direction.
#define SELECT64(M,A,B,C,T) \
	VANDPD A,M,C; \
	VANDNPD B,M,T; \
	VORPD T,C,C

#define COMPLEX_MUL_WIDE \
	VMOVDDUP Y1,Y2; \
	VPERMILPD $15,Y1,Y3; \
	VPERMILPD $5,Y0,Y4; \
	VMULPD Y2,Y0,Y0; \
	VMULPD Y3,Y4,Y4; \
	VADDSUBPD Y4,Y0,Y0

// Y0/Y1 contain the two wide operands; Y4 contains the result.
// The zero-denominator selection retains component-wise division by +0.
#define COMPLEX_DIV_WIDE(STORE) \
	VMOVDDUP Y1,Y2; \
	VPERMILPD $15,Y1,Y3; \
	VANDPD Y14,Y2,Y4; \
	VANDPD Y14,Y3,Y5; \
	VCMPPD $29,Y5,Y4,Y6; \
	VXORPD Y13,Y13,Y13; \
	VCMPPD $0,Y13,Y4,Y10; \
	VCMPPD $0,Y13,Y5,Y11; \
	VANDPD Y10,Y11,Y12; \
	SELECT64(Y6,Y2,Y3,Y7,Y8); \
	SELECT64(Y6,Y3,Y2,Y9,Y8); \
	VDIVPD Y7,Y9,Y10; \
	VMULPD Y10,Y9,Y9; \
	VADDPD Y9,Y7,Y7; \
	VDIVPD Y7,Y15,Y7; \
	VPERMILPD $5,Y0,Y1; \
	SELECT64(Y6,Y0,Y1,Y2,Y8); \
	VPERMILPD $5,Y2,Y3; \
	VMULPD Y10,Y3,Y3; \
	VADDPD Y3,Y2,Y4; \
	VSUBPD Y3,Y2,Y5; \
	VSUBPD Y2,Y3,Y9; \
	SELECT64(Y6,Y5,Y9,Y1,Y8); \
	VBLENDPD $10,Y1,Y4,Y4; \
	VMULPD Y7,Y4,Y4; \
	VMOVMSKPD Y12,AX; \
	TESTQ AX,AX; \
	JZ STORE; \
	VDIVPD Y13,Y0,Y0; \
	SELECT64(Y12,Y0,Y4,Y5,Y8); \
	VMOVUPD Y5,Y4

TEXT ·complex128AVX(SB),NOSPLIT,$0-73
	MOVQ dst_base+0(FP),DI
	MOVQ x_base+24(FP),SI
	MOVQ y_base+48(FP),DX
	MOVQ dst_len+8(FP),CX
	SHRQ $1,CX
	CMPB op+72(FP),$3
	JE cdiv
cmulLoop:
	VMOVUPD (SI),Y0
	VMOVUPD (DX),Y1
	COMPLEX_MUL_WIDE
	VMOVUPD Y0,(DI)
	ADDQ $32,SI
	ADDQ $32,DX
	ADDQ $32,DI
	DECQ CX
	JNZ cmulLoop
	VZEROUPPER
	RET
cdiv:
	VBROADCASTSD ·absMask(SB),Y14
	VBROADCASTSD ·one64(SB),Y15
cdivLoop:
	VMOVUPD (SI),Y0
	VMOVUPD (DX),Y1
	COMPLEX_DIV_WIDE(cdivStore)
cdivStore:
	VMOVUPD Y4,(DI)
	ADDQ $32,SI
	ADDQ $32,DX
	ADDQ $32,DI
	DECQ CX
	JNZ cdivLoop
	VZEROUPPER
	RET

