// x86 min/max choose y on equality and return y when either arg is
// NaN. Repair the left-NaN case with an unordered self-comparison.
#define EXTREMA(OP,LOAD,CMP,AND,ANDN,OR) \
	LOAD (SI),Y0; \
	LOAD (DX),Y1; \
	OP Y1,Y0,Y2; \
	CMP $3,Y0,Y0,Y3; \
	AND Y0,Y3,Y0; \
	ANDN Y2,Y3,Y2; \
	OR Y0,Y2,Y2; \
	LOAD Y2,(DI); \
	ADDQ $32,SI; \
	ADDQ $32,DX; \
	ADDQ $32,DI; \
	DECQ CX

TEXT ·extrema64AVX(SB),NOSPLIT,$0-73
