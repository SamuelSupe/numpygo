	CMPB maximum+72(FP),$0
	JNE max64
min64:
	EXTREMA(VMINPD,VMOVUPD,VCMPPD,VANDPD,VANDNPD,VORPD)
	JNZ min64
	VZEROUPPER
	RET
max64:
	EXTREMA(VMAXPD,VMOVUPD,VCMPPD,VANDPD,VANDNPD,VORPD)
	JNZ max64
	VZEROUPPER
	RET

